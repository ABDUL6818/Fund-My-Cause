/**
 * Resolve a contract error message for a given locale, falling back to
 * the default English message when a translation is missing.
 */
export function getContractErrorMessage(key: ContractErrorKey, locale: Locale = defaultLocale): string {
  const localized = localeMessages[locale]?.[key];
  return localized ?? contractErrorMessages[key];
}